"""Loader for the evaluation test collection (queries + qrels).

The dataset lives as two JSON files so it can be edited, version-controlled and
extended by hand (or regenerated by a script):

    data/evaluation/eval_queries.json
        [{"query_id": "q01", "text": "¿qué es la insulina ...?"}, ...]

    data/evaluation/eval_qrels.json
        {"q01": {"doc_id_a": 2, "doc_id_b": 1}, "q02": {...}}

The qrels grade convention follows the NDCG lecture: 2 = highly relevant,
1 = relevant, absent = not relevant.
"""

from __future__ import annotations

import json
from pathlib import Path

from .models import EvalQuery, EvaluationDataset

# Default location of the bundled test collection (repo-relative).
DEFAULT_QUERIES_PATH = Path("data/evaluation/eval_queries.json")
DEFAULT_QRELS_PATH = Path("data/evaluation/eval_qrels.json")


def load_dataset(
    queries_path: str | Path = DEFAULT_QUERIES_PATH,
    qrels_path: str | Path = DEFAULT_QRELS_PATH,
) -> EvaluationDataset:
    """Load queries and relevance judgments from disk.

    Args:
        queries_path: Path to the queries JSON array.
        qrels_path: Path to the qrels JSON object.

    Returns:
        A populated :class:`EvaluationDataset`.

    Raises:
        FileNotFoundError: If either file is missing.
        ValueError: If a query is missing required fields, or a qrels entry
            references a query_id that has no matching query.
    """
    queries_path = Path(queries_path)
    qrels_path = Path(qrels_path)

    if not queries_path.exists():
        raise FileNotFoundError(f"Queries file not found: {queries_path}")
    if not qrels_path.exists():
        raise FileNotFoundError(f"Qrels file not found: {qrels_path}")

    raw_queries = json.loads(queries_path.read_text(encoding="utf-8"))
    raw_qrels = json.loads(qrels_path.read_text(encoding="utf-8"))

    queries: list[EvalQuery] = []
    for entry in raw_queries:
        if "query_id" not in entry or "text" not in entry:
            raise ValueError(
                f"Query entry missing 'query_id' or 'text': {entry!r}"
            )
        queries.append(EvalQuery(query_id=entry["query_id"], text=entry["text"]))

    # Normalize grades to int and validate the join with queries.
    query_ids = {q.query_id for q in queries}
    qrels: dict[str, dict[str, int]] = {}
    for query_id, judgments in raw_qrels.items():
        if query_id not in query_ids:
            raise ValueError(
                f"qrels references unknown query_id {query_id!r} "
                f"(no matching entry in {queries_path})"
            )
        qrels[query_id] = {doc_id: int(grade) for doc_id, grade in judgments.items()}

    return EvaluationDataset(queries=queries, qrels=qrels)
